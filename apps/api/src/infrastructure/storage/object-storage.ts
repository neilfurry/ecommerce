import type { Readable } from 'node:stream';

export interface PutObjectInput {
  key: string;
  body: Buffer | Readable;
  contentType: string;
  /** Required when body is a stream. */
  contentLength?: number;
  /** Small string metadata stored with the object (x-amz-meta-*). */
  metadata?: Record<string, string>;
  /** Stored Content-Disposition, e.g. attachment; filename="receipt.pdf". */
  contentDisposition?: string;
}

export interface ObjectMetadata {
  key: string;
  contentType: string;
  contentLength: number;
  etag: string | undefined;
  lastModified: Date | undefined;
  metadata: Record<string, string>;
}

export interface StoredObject extends ObjectMetadata {
  body: Readable;
}

export interface SignedDownloadOptions {
  expiresInSeconds?: number;
  /** Forces the browser to download with this file name. */
  downloadFileName?: string;
}

export interface SignedUploadOptions {
  contentType: string;
  expiresInSeconds?: number;
}

export interface SignedUrl {
  url: string;
  expiresAt: Date;
}

/**
 * Provider-neutral object storage. Domain code depends on this abstract class (it is also
 * the DI token); S3ObjectStorage implements it for any S3-compatible service (MinIO
 * locally, AWS S3 / R2 / Spaces in production). Keys are always generated by the server.
 */
export abstract class ObjectStorage {
  abstract readonly bucket: string;

  abstract putObject(input: PutObjectInput): Promise<{ etag: string | undefined }>;

  /** Throws ObjectNotFoundError when the key does not exist. */
  abstract getObject(key: string): Promise<StoredObject>;

  /** Returns null when the key does not exist. */
  abstract headObject(key: string): Promise<ObjectMetadata | null>;

  /** Idempotent: deleting a missing key succeeds. */
  abstract deleteObject(key: string): Promise<void>;

  abstract getSignedDownloadUrl(key: string, options?: SignedDownloadOptions): Promise<SignedUrl>;

  /** For direct browser-to-storage uploads (used from Phase 4). */
  abstract getSignedUploadUrl(key: string, options: SignedUploadOptions): Promise<SignedUrl>;

  /** Throws if storage or the bucket is unreachable. Used by /health. */
  abstract assertReachable(): Promise<void>;
}

export class ObjectNotFoundError extends Error {
  constructor(readonly key: string) {
    super(`Object not found: ${key}`);
    this.name = 'ObjectNotFoundError';
  }
}
